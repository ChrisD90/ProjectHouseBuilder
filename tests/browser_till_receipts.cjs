const {chromium,expect}=require('../frontend/node_modules/@playwright/test');
const assert=require('node:assert/strict');
const base=process.env.PHB_TEST_URL;
if(!base)throw Error('Use dev/ui_browser_smoke.py.');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 try {
  const page=await browser.newPage({locale:'de-DE',viewport:{width:1280,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const owner=(await(await page.request.post(base+'/api/projects',{data:{title:'Kassenzettel-Workflow'}})).json()).project.id;
  const headers={'X-PHB-Project':String(owner)};
  await page.goto(base+'/p/'+owner+'/belege');
  const frame=page.frameLocator('iframe[title="Rechnungen & Belege"]:not([hidden])');
  await expect(frame.locator('#openReceiptWorkflow')).toHaveText('+ Rechnung erfassen');
  await frame.locator('#openTillReceiptWorkflow').click();
  await expect(frame.locator('#receiptWorkflowTitle')).toHaveText('Kassenzettel hochladen');
  await frame.locator('#upload input[type=file]').setInputFiles({name:'bon.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\nTill test')});
  await frame.locator('#receiptUploadButton').click();
  await expect(frame.locator('#receiptWorkflowTitle')).toHaveText('Kassenzettel prüfen',{timeout:30000});
  await expect(frame.locator('#categories')).toHaveValue('Eigenleistungen / Material');
  await expect(frame.locator('#receiptAssignmentType')).toHaveValue('Eigenleistung');
  await expect(frame.locator('#tillFinancingSource')).toHaveValue('unassigned');
  await expect(frame.locator('#billingType')).toBeHidden();
  await expect(frame.locator('#review [name=due_date]')).toBeHidden();
  await expect(frame.locator('[data-flow-step="2"]')).toBeHidden();
  await frame.locator('#review [name=supplier]').fill('OBI');
  await frame.locator('#review [name=invoice_number]').fill('BON-123');
  await frame.locator('#review [name=document_date]').fill('2026-11-03');
  await frame.locator('#receiptTaxRate').selectOption('19');
  await frame.locator('#receiptGross').fill('119,00');
  await frame.locator('#book').click();
  const confirm=frame.locator('dialog.phb-messagebox');
  await expect(confirm).toContainText('beim Einkauf bezahlt');
  await confirm.getByRole('button',{name:'Abbrechen',exact:true}).click();
  let rows=(await(await page.request.get(base+'/api/receipts',{headers})).json()).receipts;
  assert.equal(rows[0].status,'Entwurf');assert.equal(rows[0].paid_amount,0);
  await frame.locator('#book').click();
  await confirm.getByRole('button',{name:'Bestätigen',exact:true}).click();
  await expect(frame.locator('#receiptReviewState')).toHaveText('Gebucht');
  await expect(frame.locator('#saveReceiptDraft')).toBeEnabled();
  rows=(await(await page.request.get(base+'/api/receipts',{headers})).json()).receipts;
  assert.equal(rows[0].paid_amount,119);assert.equal(rows[0].net_amount,100);assert.equal(rows[0].vat_amount,19);
  assert.equal(rows[0].payment_assignment,'Nicht zugewiesen');
  await expect(frame.locator('#receiptWorkflowDialog')).toHaveAttribute('data-phb-stage','1');
  await frame.locator('#payReceipt').click();
  await expect(frame.locator('#receiptPaymentTitle')).toHaveText('Zahlung / Finanzierung verwalten');
  await expect(frame.locator('#receiptPaymentForm')).toBeHidden();
  await expect(frame.locator('#receiptPaymentHistory')).toContainText('Nicht zugewiesen');
  await frame.locator('#closeReceiptPayment').click();
  await expect(frame.locator('[data-flow-step="2"]')).toBeHidden();
  await frame.locator('#closeReceiptWorkflow').click();
  await frame.locator('#openReceiptWorkflow').click();
  await frame.locator('#upload input[type=file]').setInputFiles({name:'rechnung.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\nInvoice test')});
  await frame.locator('#receiptUploadButton').click();
  await expect(frame.locator('#review [name=kind]')).toHaveValue('Rechnung',{timeout:30000});
  await expect(frame.locator('#billingType')).toBeVisible();
  await expect(frame.locator('#review [name=due_date]')).toBeVisible();
  await expect(frame.locator('[data-flow-step="2"]')).toBeVisible();
  await frame.locator('#closeReceiptWorkflow').click();
  const firstAccount=(await(await page.request.post(base+'/api/financing/equity',{headers,data:{name:'Baukonto A',opening_balance:500,reserve:0}})).json()).id;
  const secondAccount=(await(await page.request.post(base+'/api/financing/equity',{headers,data:{name:'Baukonto B',opening_balance:200,reserve:0}})).json()).id;
  const extra=await page.request.post(base+'/api/receipts',{headers,multipart:{receipt_kind:'Kassenzettel',file:{name:'bon-konto.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\nTill financing')}}});
  assert.equal(extra.status(),201,await extra.text());const rid=(await extra.json()).id;
  await page.goto(base+'/p/'+owner+'/belege?receipt_id='+rid);
  await expect(frame.locator('#tillFinancingSource')).toHaveValue('equity:'+firstAccount);
  await frame.locator('#tillFinancingSource').selectOption('equity:'+secondAccount);
  await frame.locator('#saveReceiptDraft').click();
  await expect(frame.locator('#receiptSaveStatus')).toContainText('Entwurf gespeichert.');
  await expect(frame.locator('#tillFinancingSource')).toHaveValue('equity:'+secondAccount);
  await expect(frame.locator('#saveReceiptDraft')).toBeEnabled();
  await frame.locator('#review [name=supplier]').fill('Baumarkt');
  await frame.locator('#review [name=document_date]').fill('2026-11-03');
  await frame.locator('#receiptGross').fill('50,00');
  await frame.locator('#review [name=kind]').evaluate(n=>n.disabled=true);
  const bookingURL='**/api/receipts/'+rid+'/book-till';
  await page.route(bookingURL,route=>route.fulfill({status:404,contentType:'application/json',body:JSON.stringify({error:'Route fehlt',code:'http_404'})}));
  await frame.locator('#book').click();
  await confirm.getByRole('button',{name:'Bestätigen',exact:true}).click();
  await expect(frame.locator('#receiptSaveStatus')).toContainText('Bitte die App neu starten');
  const untouched=(await(await page.request.get(base+'/api/receipts/'+rid,{headers})).json());
  assert.equal(untouched.status,'Entwurf');assert.equal(untouched.paid_amount,0);
  await page.unroute(bookingURL);
  const booking=page.waitForRequest(r=>r.url().endsWith('/api/receipts/'+rid+'/book-till')&&r.method()==='POST');
  await frame.locator('#book').click();
  await expect(confirm).toContainText('Baukonto B');
  await confirm.getByRole('button',{name:'Bestätigen',exact:true}).click();
  const request=(await booking).postDataJSON();
  assert.equal(request.kind,'Kassenzettel');assert.equal(request.till_financing.equity_id,secondAccount);
  await expect(frame.locator('#receiptReviewState')).toHaveText('Gebucht');
  const finance=(await(await page.request.get(base+'/api/financing',{headers})).json());
  const payment=finance.payments.find(p=>p.receipt_id===rid);
  assert.equal(payment.equity_id,secondAccount);assert.equal(payment.amount,50);
  assert.equal(finance.equity.find(a=>a.id===firstAccount).balance.available,500);
  assert.equal(finance.equity.find(a=>a.id===secondAccount).balance.available,150);
  assert.deepEqual(errors,[]);
  console.log('PASS separate receipt uploads, compact till defaults, confirmation cancellation, one paid booking and unchanged invoice review.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
