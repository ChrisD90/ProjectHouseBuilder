const {chromium,expect}=require('../frontend/node_modules/@playwright/test');
const assert=require('node:assert/strict');
const base=process.env.PHB_TEST_URL;
if(!base)throw Error('Use dev/ui_browser_smoke.py.');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage({locale:'de-DE',viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 try{
  const owner=(await(await page.request.post(base+'/api/projects',{data:{title:'Rechnungszuordnung'}})).json()).project.id;
  const headers={'X-PHB-Project':String(owner)};
  async function post(path,data){const response=await page.request.post(base+path,{headers,data});assert(response.ok(),await response.text());return response.json();}
  const company=(await post('/api/contractors',{name:'Malerbetrieb Test',trade:'Maler & Lackierer'})).contractor.id;
  const other=(await post('/api/contractors',{name:'Elektrobetrieb Test',trade:'Elektro'})).contractor.id;
  const offer=(await post('/api/offers/manual',{vendor:'Malerbetrieb Test',contractor_id:company,gross:1200,category:'Sonstiges'})).offer;
  const accepted=await page.request.post(base+'/api/offers/'+offer.id+'/accept',{headers,form:{mode:'offer',confirm:'true'}});
  assert.equal(accepted.status(),201,await accepted.text());
  const upload=await page.request.post(base+'/api/receipts',{headers,multipart:{analysis_mode:'none',file:{name:'Zuordnung.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\nZuordnung')}}});
  assert.equal(upload.status(),201,await upload.text());const rid=(await upload.json()).id;
  await page.goto(base+'/p/'+owner+'/belege?receipt_id='+rid);
  const frame=page.frameLocator('iframe[title="Rechnungen & Belege"]:not([hidden])');
  await expect(frame.locator('#receiptWorkflowDialog')).toBeVisible();
  await expect(frame.locator('#receiptReviewStage')).not.toBeVisible();
  assert.deepEqual(await frame.locator('#receiptAssignmentType option:not([hidden])').evaluateAll(options=>options.map(option=>option.value).filter(Boolean)),['Angebot','Betrieb']);
  assert.equal(await frame.locator('#review').evaluate(form=>[...form.querySelectorAll('input,select,textarea')].find(node=>node.getBoundingClientRect().height>0).id),'receiptAssignmentType');
  await frame.locator('#receiptAssignmentType').selectOption('Betrieb');
  await expect(frame.locator('#receiptSupplierCompany')).toBeVisible();
  await expect(frame.locator('#receiptTrade')).toBeVisible();
  await expect(frame.locator('#costItems')).toBeHidden();
  await expect(frame.locator('#categories')).toBeHidden();
  await expect(frame.locator('#budgetLines')).toBeHidden();
  await expect(frame.locator('[name=supplier]')).toBeHidden();
  await frame.locator('#receiptSupplierCompany').selectOption(String(company));
  await expect(frame.locator('#receiptTrade')).toHaveValue('Maler & Lackierer');
  await frame.locator('#receiptTrade').selectOption('Sonstiges');
  await frame.locator('#billingType').selectOption('Abschlagsrechnung');
  await expect(frame.locator('#receiptTrade')).toHaveValue('Sonstiges');
  await frame.locator('#receiptSupplierCompany').selectOption(String(other));
  await expect(frame.locator('#receiptTrade')).toHaveValue('Elektro');
  await frame.locator('#saveReceiptDraft').click();
  await expect(frame.locator('#receiptSaveStatus')).toContainText('Entwurf gespeichert.');
  let saved=await(await page.request.get(base+'/api/receipts/'+rid,{headers})).json();
  assert.equal(saved.contractor_id,other);assert.equal(saved.trade,'Elektro');assert.equal(saved.supplier,'Elektrobetrieb Test');
  await frame.locator('#receiptAssignmentType').selectOption('Angebot');
  await expect(frame.locator('#costItems')).toBeVisible();
  await expect(frame.locator('#receiptSupplierCompany')).toBeHidden();
  await expect(frame.locator('#receiptTrade')).toBeHidden();
  const overview=await(await page.request.get(base+'/api/costs',{headers})).json();
  const item=overview.items.find(item=>item.offer_id===offer.id);
  await frame.locator('#costItems').selectOption(String(item.id));
  await frame.locator('[name=document_date]').fill('2026-11-04');
  await frame.locator('#receiptGross').fill('120,00');
  await frame.locator('#saveReceiptDraft').click();
  await expect(frame.locator('#receiptSaveStatus')).toContainText('Entwurf gespeichert.');
  saved=await(await page.request.get(base+'/api/receipts/'+rid,{headers})).json();
  assert.equal(saved.cost_item_id,item.id);assert.equal(saved.contractor_id,null);
  assert.equal(saved.supplier,'Malerbetrieb Test');assert.equal(saved.trade,'Maler & Lackierer');
  const date=await frame.locator('[name=document_date]').boundingBox(),due=await frame.locator('[name=due_date]').boundingBox();
  assert(Math.abs(date.y-due.y)<2&&date.x+date.width<=due.x);
  const amounts=await Promise.all(['receiptGross','receiptNet','receiptVat'].map(id=>frame.locator('#'+id).boundingBox()));
  assert(amounts.every(rect=>Math.abs(rect.y-amounts[0].y)<2));
  await page.screenshot({path:'/tmp/phb-receipt-attribution.png'});
  await frame.locator('#receiptAssignmentType').selectOption('Betrieb');
  await frame.locator('#receiptSupplierCompany').selectOption(String(other));
  await frame.locator('#saveReceiptDraft').click();
  await expect(frame.locator('#receiptSaveStatus')).toContainText('Entwurf gespeichert.');
  saved=await(await page.request.get(base+'/api/receipts/'+rid,{headers})).json();
  assert.equal(saved.cost_item_id,null);assert.equal(saved.contractor_id,other);assert.equal(saved.trade,'Elektro');
  await frame.locator('#receiptSupplierCompany').selectOption('');
  await expect(frame.locator('[name=supplier]')).toHaveValue('');
  await frame.locator('#receiptSupplierCompany').selectOption(String(other));
  await frame.locator('#saveReceiptDraft').click();
  await expect(frame.locator('#receiptSaveStatus')).toContainText('Entwurf gespeichert.');
  await page.setViewportSize({width:390,height:844});
  await expect(frame.locator('#receiptWorkflowDialog')).toBeVisible();
  assert(await frame.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await expect(frame.locator('[name=document_date]')).toBeVisible();
  await expect(frame.locator('[name=due_date]')).toBeVisible();
  assert.deepEqual(errors,[]);
  console.log('PASS restricted invoice attribution, company trade defaults and overrides, persisted offer/company links, compact dates/amounts and mobile layout.');
 }catch(error){await page.screenshot({path:'/tmp/phb-receipt-attribution-failure.png'});throw error;}
 finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
