const {chromium,expect}=require('../frontend/node_modules/@playwright/test');
const assert=require('node:assert/strict');
const base=process.env.PHB_TEST_URL;
if(!base)throw Error('Use dev/ui_browser_smoke.py.');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 try {
  const page=await browser.newPage();
  const owner=(await(await page.request.post(base+'/api/projects',{data:{title:'DIY Upload'}})).json()).project.id;
  const headers={'X-PHB-Project':String(owner)};
  const task=(await(await page.request.post(base+'/api/tasks',{headers,data:{code:'D1',name:'Zimmer streichen',trade:'Maler & Lackierer',execution_type:'Eigenleistung',duration:1}})).json()).id;
  const plan=(await(await page.request.post(base+'/api/self-work',{headers,data:{title:'Wände streichen',description:'Kachelfläche anklicken',task_id:task,status:'Erledigt'}})).json()).plan;
  const second=(await(await page.request.post(base+'/api/self-work',{headers,data:{title:'Boden verlegen'}})).json()).plan;
  await page.goto(base+'/p/'+owner+'/eigenleistungen');
  const status=page.getByRole('textbox',{name:'Status',exact:true});
  await status.click();await page.getByRole('option',{name:'Geplant',exact:true}).click();
  await expect(page.getByRole('button',{name:'Eigenleistung bearbeiten: Wände streichen',exact:true})).toHaveCount(0);
  await status.click();await page.getByRole('option',{name:'Erledigt',exact:true}).click();
  const green=await page.locator('.self-work-status').evaluate(n=>getComputedStyle(n).color);
  const rgb=green.match(/[\d.]+/g).map(Number);assert(rgb[1]>rgb[0]&&rgb[1]>rgb[2]);
  await status.click();await page.getByRole('option',{name:'Alle Status',exact:true}).click();
  await page.locator('.self-work-card').getByText('Kachelfläche anklicken',{exact:true}).click();
  const edit=page.getByRole('dialog',{name:'Eigenleistung bearbeiten',exact:true});
  await expect(edit).toBeVisible();
  await expect(edit.getByRole('button',{name:'Speichern',exact:true})).toBeVisible();
  await edit.getByRole('button',{name:'Schließen',exact:true}).click();
  await page.getByRole('button',{name:'Rechnungen zu Wände streichen: 0',exact:true}).click();
  const invoices=page.getByRole('dialog',{name:'Rechnungen · Wände streichen',exact:true});
  await expect(invoices).toBeVisible();
  assert((await invoices.boundingBox()).width>=1100,'Eigenleistungsbelege sollen im breiten Rechnungsdialog öffnen.');
  await expect(invoices.locator('.mantine-SimpleGrid-root')).toHaveCount(0);
  await expect(invoices.getByText('Dieser Eigenleistung sind noch keine Rechnungen zugeordnet.')).toBeVisible();
  await expect(edit).toHaveCount(0);
  await invoices.getByRole('button',{name:'Neue Rechnung zuordnen',exact:true}).click();
  const frame=page.frameLocator('iframe[title="Rechnungen & Belege"]:not([hidden])');
  await expect(frame.locator('#receiptWorkflowDialog')).toBeVisible();
  await expect(frame.locator('#receiptWorkflowTitle')).toHaveText('Beleg zur Eigenleistung erfassen');
  await expect(frame.locator('#uploadStatus')).toContainText('Wände streichen');
  await frame.locator('#upload input[type=file]').setInputFiles({name:'material.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\nDIY test')});
  await frame.locator('#receiptUploadButton').click();
  await expect(frame.locator('#receiptAssignmentType')).toHaveValue('Eigenleistung',{timeout:30000});
  await expect(frame.locator('#receiptTrade')).toHaveValue('Maler & Lackierer');
  await expect(frame.locator('#receiptSelfWork')).toHaveValue(String(plan.id));
  const saved=(await(await page.request.get(base+'/api/self-work/'+plan.id,{headers})).json()).plan;
  assert.equal(saved.receipt_ids.length,1);
  assert.equal(saved.actual_cost,0);
  await frame.locator('#receiptSelfWork').selectOption(String(second.id));
  await frame.locator('#saveReceiptDraft').click();
  await expect.poll(async()=>{
    return (await(await page.request.get(base+'/api/self-work/'+second.id,{headers})).json()).plan.receipt_ids.length;
  }).toBe(1);
  await expect(frame.locator('#saveReceiptDraft')).toBeEnabled();
  await expect(frame.locator('#receiptSaveStatus')).toContainText('Entwurf gespeichert.');
  await page.getByRole('link',{name:'Eigenleistungen',exact:true}).click();
  await page.getByRole('button',{name:'Rechnungen zu Boden verlegen: 1',exact:true}).click();
  const linked=page.getByRole('dialog',{name:'Rechnungen · Boden verlegen',exact:true});
  await expect(linked.getByRole('columnheader',{name:'Angerechnet',exact:true})).toBeVisible();
  await expect(linked.getByRole('link',{name:'Original ansehen',exact:true})).toBeVisible();
  console.log('PASS whole DIY card, independent invoice action, direct contextual upload and persisted draft attribution.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
