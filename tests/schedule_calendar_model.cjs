const assert=require('node:assert/strict');
const M=require('../static/schedule_calendar_model.js');
assert(M.valid('2028-02-29'));assert(!M.valid('2027-02-29'));assert(!M.valid('2026-11-31'));
assert.equal(M.monday('2027-01-03'),'2026-12-28');
assert.equal(M.add('2028-02-28',2),'2028-03-01');
assert.equal(M.distance('2026-03-28','2026-03-30'),2);
assert.deepEqual(M.period('month','2021-02-17'),{start:'2021-02-01',end:'2021-02-28'});
assert.deepEqual(M.period('month','2026-11-15'),{start:'2026-10-26',end:'2026-12-06'});
assert.deepEqual(M.period('week','2026-11-15'),{start:'2026-11-09',end:'2026-11-15'});
assert.equal(M.month('2026-12-31',1),'2027-01-01');
const tasks=[{id:1,start:'2026-11-08',end:'2026-11-11'},{id:2,start:'2026-11-09',end:'2026-11-10'},{id:3,start:'2026-11-12',end:'2026-11-18'},{id:4,start:'2026-12-01',end:'2026-12-02'}];
const original=JSON.stringify(tasks),bars=M.segments(tasks,'2026-11-09','2026-11-15');
assert.equal(JSON.stringify(tasks),original);assert.equal(bars.length,3);
assert.equal(bars[0].column,0);assert.equal(bars[0].span,3);assert.equal(bars[0].continuesBefore,true);
assert.equal(bars[1].lane,1);assert.equal(bars[2].lane,0);assert.equal(bars[2].continuesAfter,true);
for(const a of bars)for(const b of bars)if(a!==b&&a.lane===b.lane)assert(a.end<b.start||b.end<a.start);
assert(M.intersects(tasks[0],'2026-11-11','2026-11-11'));
assert(!M.intersects(tasks[0],'2026-11-12','2026-11-12'));
assert(M.quickMatch({status:'Offen'},'open-end','2026-11-10'));
assert(!M.quickMatch({status:'Erledigt'},'open-end','2026-11-10'));
assert(!M.quickMatch({status:'Offen',end:'2026-01-01'},'overdue','2026-11-10'));
assert(M.quickMatch({status:'Offen',planned_end:'2026-11-09'},'overdue','2026-11-10'));
assert(!M.quickMatch({status:'Erledigt',planned_end:'2026-11-09'},'overdue','2026-11-10'));
assert(M.quickMatch({status:'In Arbeit',start:'2025-01-01',end:'2025-01-02'},'week','2026-11-10'));
console.log('PASS calendar date boundaries, clipped segments, non-overlapping lanes and deadline/running filters.');
